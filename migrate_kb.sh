#!/bin/bash
# Knowledge-base migration — one command, knowledge only.
#
#   bash migrate_kb.sh                                  diagnose this install
#   bash migrate_kb.sh --from /old/data/documents        diagnose, planning a copy from there
#   bash migrate_kb.sh --apply                           do it (this install)
#   bash migrate_kb.sh --from /old/data/documents --apply do it (copy first, then migrate)
#
# SCOPE — this migrates the knowledge base and nothing else:
#
#   in : data/documents/project_<id>/          the files
#        data/documents/.kvmeta/project_<id>.json   the index the panel lists from
#        `projects` rows                        the rows that make a project reachable
#        recorded path strings                  the absolute paths that dangle after a move
#
#   out: Registry  (agents, custom tools, skills, models, directives, settings documents)
#        Workspace (sessions, checkpoints, workspace_files, memories, logs)
#        data/documents/project_chat_sessions/  chat attachments, not a project
#        storage_objects and the RAG index      unused in local mode; regenerated by re-indexing
#
# It writes nothing unless --apply is given. Every write it performs has a reverse:
# relocate_knowledge_paths.py --rollback and adopt_orphan_projects.py --undo.
#
# Order matters and is not arbitrary: the panel lists projects from the database, and doctor.sh
# refuses to adopt while any recorded path is dangling. So the paths are rewritten BEFORE the
# rows are created, or neither step can succeed.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
BE="$ROOT/backend"
PY="$BE/.venv/bin/python"

FROM=""
APPLY=0
for arg in "$@"; do
    case "$arg" in
        --from)  FROM="__next__" ;;
        --apply) APPLY=1 ;;
        *)
            if [ "$FROM" = "__next__" ]; then
                FROM="$arg"
            else
                echo "unknown argument: $arg" >&2
                echo "usage: bash migrate_kb.sh [--from <old documents dir>] [--apply]" >&2
                exit 2
            fi
            ;;
    esac
done
[ "$FROM" = "__next__" ] && { echo "--from needs a directory" >&2; exit 2; }

if [ ! -x "$PY" ]; then
    echo "✗ no virtualenv at backend/.venv"
    echo "  create it first:  cd backend && uv sync"
    exit 1
fi

cd "$BE" || exit 1

if [ "$APPLY" = "1" ]; then
    echo "══ APPLY — writing changes ══════════════════════════════════════════"
else
    echo "══ DRY RUN — nothing will be written (add --apply to perform it) ════"
fi

# ── 0. where this install keeps its knowledge, and in which mode ────────────
echo
echo "── 0. this install ─────────────────────────────────────────────────"
DOCS="$("$PY" - <<'EOF'
from services.file_storage import file_storage
print(str(file_storage.base_dir))
EOF
)"
MODE_ENV="$("$PY" -c 'from config import settings; print(settings.storage_mode)' 2>/dev/null)"
MODE_DOC="$("$PY" - <<'EOF' 2>/dev/null
from core.settings import store
from db.database import SessionLocal
db = SessionLocal()
print((store.get_document(db, "storage") or {}).get("mode"))
db.close()
EOF
)"
echo "   documents root : $DOCS"
echo "   mode (.env)    : ${MODE_ENV:-unset}"
echo "   mode (settings): ${MODE_DOC:-unset}"
if [ "$MODE_ENV" = "db" ] || [ "$MODE_DOC" = "db" ]; then
    echo
    echo "   ⚠ storage mode is 'db' on this install."
    echo "     The Knowledge panel then lists documents from storage_objects in Postgres, not from"
    echo "     .kvmeta on disk, so a copied folder will not appear no matter how complete it is."
    echo "     For this migration to be verifiable, set mode to 'local' in Settings → Storage AND"
    echo "     STORAGE_MODE=local in .env (standalone scripts read only .env), then re-run."
fi

# ── 1. inventory ────────────────────────────────────────────────────────────
echo
echo "── 1. inventory ────────────────────────────────────────────────────"
"$PY" scripts/audit_local_data.py || exit 1

# ── 2. copy, when a source was given ────────────────────────────────────────
echo
echo "── 2. copy from the old install ────────────────────────────────────"
if [ -z "$FROM" ]; then
    echo "   no --from given: assuming the folder is already in place."
    echo "   (pass --from /old/data/documents to have this step copy it)"
else
    if [ ! -d "$FROM" ]; then
        echo "✗ $FROM is not a directory" >&2
        exit 1
    fi
    copied=0
    for src in "$FROM"/project_*/; do
        [ -d "$src" ] || continue
        name="$(basename "$src")"
        # project_chat_sessions is the chat attachment container, not a project (scope rule)
        if ! [[ "$name" =~ ^project_[0-9]+$ ]]; then
            echo "   skip $name (not a numeric project folder)"
            continue
        fi
        if [ "$APPLY" = "1" ]; then
            # Copy the CONTENTS into a directory we name ourselves. `cp -a "$src" "$DOCS/"`
            # looks equivalent and is a trap: BSD cp (macOS) with a trailing slash on the
            # source copies its contents, flattening every document into the documents root,
            # while GNU cp (Ubuntu) creates $DOCS/$name. Same command, two different trees,
            # both reporting success.
            mkdir -p "$DOCS/$name"
            if ! cp -a "${src%/}/." "$DOCS/$name/"; then
                echo "   ✗ cp failed for $name" >&2
                exit 1
            fi
            # And prove it landed. An empty folder plus an intact .kvmeta record passes every
            # later check in this script, so a silent copy failure would be adopted as a project
            # with no documents in it.
            src_n="$(find "${src%/}" -type f 2>/dev/null | wc -l | tr -d ' ')"
            dst_n="$(find "$DOCS/$name" -type f 2>/dev/null | wc -l | tr -d ' ')"
            if [ "$src_n" != "$dst_n" ]; then
                echo "   ✗ $name: $dst_n of $src_n file(s) arrived — stopping" >&2
                exit 1
            fi
            echo "   $name: $dst_n file(s)"
        fi
        copied=$((copied + 1))
    done
    kv=0
    if [ -d "$FROM/.kvmeta" ]; then
        kv="$(ls "$FROM"/.kvmeta/project_*.json 2>/dev/null | wc -l | tr -d ' ')"
        if [ "$APPLY" = "1" ]; then
            mkdir -p "$DOCS/.kvmeta"
            cp -a "$FROM"/.kvmeta/project_*.json "$DOCS/.kvmeta/" 2>/dev/null
        fi
    fi
    if [ "$APPLY" = "1" ]; then
        echo "   copied $copied project folder(s) and $kv .kvmeta record file(s) into $DOCS"
    else
        echo "   would copy $copied project folder(s) and $kv .kvmeta record file(s) into $DOCS"
    fi
    echo "   (journals are not copied: a stale relocate/adopt journal would be dangerous)"

    # A record whose path still resolves is never rewritten, by design — so while the old tree is
    # still on disk the knowledge base would keep serving documents from THERE. Say so out loud,
    # because the migration looks finished and the panel looks right.
    if [ "$APPLY" = "1" ]; then
        STALE="$("$PY" - "$DOCS" "$FROM" <<'EOF'
import glob, json, os, sys
root, old = sys.argv[1], os.path.abspath(sys.argv[2])
n = 0
for f in glob.glob(os.path.join(root, ".kvmeta", "*.json")):
    for rec in json.load(open(f)).values():
        if (rec.get("storage_path") or "").startswith(old):
            n += 1
print(n)
EOF
)"
        if [ "${STALE:-0}" != "0" ]; then
            echo
            echo "   ⚠ $STALE record(s) still name the source tree you copied from: $FROM"
            echo "     Those paths resolve, so nothing rewrites them — the panel would keep"
            echo "     serving documents from the old tree instead of this install."
            echo "     Delete or move the source tree, then re-run steps 3-5."
        fi
    fi
fi

# ── 3. rewrite recorded paths ───────────────────────────────────────────────
echo
echo "── 3. recorded paths ───────────────────────────────────────────────"
if [ "$APPLY" = "1" ]; then
    "$PY" scripts/relocate_knowledge_paths.py --apply || exit 1
else
    "$PY" scripts/relocate_knowledge_paths.py || exit 1
fi

# ── 4. adopt folders that have no project row ───────────────────────────────
echo
echo "── 4. project rows ─────────────────────────────────────────────────"
if [ "$APPLY" = "1" ]; then
    "$PY" scripts/adopt_orphan_projects.py --apply || exit 1
else
    "$PY" scripts/adopt_orphan_projects.py || exit 1
fi

# ── 5. verify ───────────────────────────────────────────────────────────────
echo
echo "── 5. verify ───────────────────────────────────────────────────────"
# Both scripts print one of two shapes, and only that pair is a reliable signal: relocate either
# says "every recorded path resolves" or prints an N/M count line, and the adopter either says
# "no orphan folders" or lists them. Matching the count line would always match, because it is
# printed even when the count is zero.
PATHS_OK=0
ORPHANS_OK=0
"$PY" scripts/relocate_knowledge_paths.py 2>/dev/null | grep -q "every recorded path resolves" && PATHS_OK=1
"$PY" scripts/adopt_orphan_projects.py 2>/dev/null | grep -q "no orphan folders" && ORPHANS_OK=1

echo "   recorded paths resolve : $([ "$PATHS_OK" = 1 ] && echo yes || echo 'NO, see step 3')"
echo "   every folder has a row : $([ "$ORPHANS_OK" = 1 ] && echo yes || echo 'NO, see step 4')"

if [ "$PATHS_OK" = 1 ] && [ "$ORPHANS_OK" = 1 ]; then
    if [ "$APPLY" = "1" ]; then
        echo
        echo "   ✓ migration complete for this install"
        echo
        echo "   One check remains, and only a browser can do it: open a document in the"
        echo "   Knowledge panel. Listing reads the index; opening reads the file."
        echo "   Search is not migrated — it returns after a re-index or a re-upload."
        echo
        echo "   Reverse this run:  backend/scripts/relocate_knowledge_paths.py --rollback"
        echo "                      backend/scripts/adopt_orphan_projects.py --undo"
    else
        echo
        echo "   ✓ nothing to fix — this install's knowledge base is already consistent"
    fi
    exit 0
fi

echo
if [ "$APPLY" = "1" ]; then
    echo "   ✗ migration incomplete"
else
    echo "   ↑ the two problems above are what --apply fixes."
fi
exit 1
