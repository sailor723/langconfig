"""merge_ttl — one TTL file for tools that only accept one file (pyLODE, WIDOCO, Protégé).

The ontology is deliberately many small files (a generated "structure" file plus a
hand-written "meaning" file per table), because that is how it is reviewed. Documentation
generators want the opposite. This writes the union to `ontology.merged.ttl` and does not
touch the sources.

It also adds the `owl:Ontology` header the sources do not declare — measured: the merged
graph had no subject of type owl:Ontology, so a generator has nothing to title the page
with. The header exists only in the merged artifact; adding one to the sources is a
separate decision.

    /Users/weiping/dev/Learn/cube/tutorial/.venv/bin/python sql-first/merge_ttl.py
    /Users/weiping/dev/Learn/cube/tutorial/.venv/bin/pylode -i sql-first/ontology.merged.ttl -o sql-first/ontology-doc.html
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import sqlgen
from rdflib import OWL, RDF, RDFS, Literal, URIRef

HERE = pathlib.Path(__file__).parent
OUT = HERE / "ontology.merged.ttl"
ONTO = URIRef(sqlgen.NS.rstrip("#"))


def main() -> int:
    graph = sqlgen.load()
    had_header = (None, RDF.type, OWL.Ontology) in graph
    if not had_header:
        graph.add((ONTO, RDF.type, OWL.Ontology))
        graph.add((ONTO, RDFS.label, Literal("Retail ontology, merged for the sql-first-style app")))
        graph.add((ONTO, RDFS.comment, Literal(
            "Union of the generated structure files and the hand-written meaning files, "
            "plus the sql-first overlay that declares :aggregate/:grain/:universe. "
            "Generated by merge_ttl.py — do not edit; edit the sources.")))
    OUT.write_text(graph.serialize(format="turtle"))

    # Two counts, so a silent truncation cannot pass: what went in, what came out.
    reloaded = sqlgen.Graph().parse(OUT, format="turtle")
    same = len(reloaded) == len(graph)
    print(f"== {OUT.name}: {len(graph)} triples in, {len(reloaded)} after a reparse")
    print(f"  owl:Ontology header: {'already declared' if had_header else 'added in this artifact only'}")
    print(f"  gate: {len(reloaded)}/{len(graph)} triples round-trip — {'PASS' if same else 'FAIL'}")
    return 0 if same else 1


if __name__ == "__main__":
    raise SystemExit(main())
