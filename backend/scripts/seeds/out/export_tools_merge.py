"""Export the live tools as an ADDITIVE, machine-agnostic seed.

Writes ``scripts/seeds/custom_tools_merge.sql``. Semantics are the union the
team asked for, keyed on ``tool_id`` (which has a unique index):

    their 5 tools  +  my 6 (3 shared, 3 new)  =  8 rows
                                                 ^ the 3 shared are NOT touched

  * **no ``id``** — the target assigns it from the sequence, so a teammate's own
    rows and ids are never disturbed and no primary key can collide;
  * **``ON CONFLICT (tool_id) DO NOTHING``** — a tool the target already has is
    left exactly as it is, including a teammate's edited copy of a shared tool;
  * built-ins are the exception and stay the installer's business:
    ``seed_builtin_tools.py`` refreshes those in place, because their code is the
    source of truth. This file only ever ADDS.

Why: ``custom_tools_dump.sql`` carries explicit ids and ``seed_all.py`` restored
it only when ``custom_tools`` was EMPTY. A teammate who had already made their
own tools therefore received none of the shared catalog — the exact case that
must not break, and must not be resolved by truncating their work either.

Usage:
    cd backend
    .venv/bin/python scripts/seeds/out/export_tools_merge.py            # write the file
    .venv/bin/python scripts/seeds/out/export_tools_merge.py --stdout   # preview
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

for _p in Path(__file__).resolve().parents:
    if (_p / "_seedpaths.py").exists():
        sys.path.insert(0, str(_p))
        break
from _seedpaths import BACKEND, IN_DIR, OUT_DIR, REPO, SEEDS  # noqa: E402

import _secretscan  # noqa: E402  (sibling module in out/)

from sqlalchemy import text                     # noqa: E402
from db.database import SessionLocal            # noqa: E402

OUT_FILE = IN_DIR / "custom_tools_merge.sql"


def lit(value) -> str:
    """A SQL literal for one value, escaped for a single-quoted string."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (dict, list)):
        return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'"
    return "'" + str(value).replace("'", "''") + "'"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--stdout", action="store_true", help="print instead of writing the file")
    ap.add_argument("--redact", action="store_true",
                    help="write the file but replace credential-shaped values with a "
                         "marker instead of refusing (the affected rows will not work "
                         "for teammates until the credential moves to Settings)")
    ap.add_argument("--out", default=str(OUT_FILE), help="output path")
    args = ap.parse_args(argv)

    db = SessionLocal()
    try:
        # Every column except the surrogate id — introspected rather than
        # hardcoded so a future migration cannot silently drop a field here.
        columns = [r[0] for r in db.execute(text(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_name = 'custom_tools' AND column_name <> 'id' "
            "ORDER BY ordinal_position"
        ))]
        rows = [dict(r._mapping) for r in db.execute(text(
            f"SELECT {', '.join(columns)} FROM custom_tools ORDER BY tool_id"
        ))]
    finally:
        db.close()

    if not rows:
        print("no tools in the database — nothing written")
        return 1

    lines = [
        "-- LangConfig additive tool seed — generated by export_tools_merge.py",
        f"-- {len(rows)} tool(s) from the live database.",
        "--",
        "-- Union semantics on tool_id: a row the target already has is left",
        "-- untouched, a missing one is added with an id from the sequence. Run it",
        "-- on a fresh database or on one already full of a teammate's tools.",
        "--",
        "--   psql \"$DATABASE_URL\" -v ON_ERROR_STOP=1 -f custom_tools_merge.sql",
        "",
        "BEGIN;",
        "",
    ]

    for row in rows:
        cols = ", ".join(columns)
        vals = ", ".join(lit(row.get(col)) for col in columns)
        lines.append(
            f"INSERT INTO custom_tools ({cols})\n"
            f"SELECT {vals}\n"
            f"WHERE NOT EXISTS (SELECT 1 FROM custom_tools WHERE tool_id = {lit(row['tool_id'])});"
        )
        lines.append("")

    lines += [
        "COMMIT;",
        "",
        f"-- done: {len(rows)} tool(s) offered; existing tool_ids were skipped.",
        "",
    ]

    sql = "\n".join(lines)

    # Never write OR print an artefact that looks like it carries a credential.
    # This runs before --stdout as well: printing to a terminal is how the value
    # would end up in a paste, a log, or a commit anyway.
    sql = _secretscan.guard(sql, source=args.out, redact_instead=args.redact)

    if args.stdout:
        print(sql)
        return 0

    Path(args.out).write_text(sql, encoding="utf-8")
    print(f"wrote {args.out} — {len(rows)} tool(s), {Path(args.out).stat().st_size / 1024:.0f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
