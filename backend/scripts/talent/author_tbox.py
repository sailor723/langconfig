#!/usr/bin/env python3
"""Write the role axioms (TBox) and the `reasoning.json` contract from what the JDs state.

A role definition is a BUSINESS statement ("2 years of order tracking and ERP"), so it cannot be
invented here — but it also must not be hand-typed per role when the client already wrote it down in ten
职务说明书. This generator turns each parsed requirement into the definition the reasoner will judge:

    :skillsFor_<Role> ≡ :CatA ⊔ :CatB ⊔ …        (a JD lists alternatives, not a conjunction)
    :matches_<Role>   ≡ :Candidate ⊓ (:hasSkill some :skillsFor_<Role>)
                       ⊓ (:yearsExperience some xsd:integer[>= N])
                       ⊓ (:educationRank  some xsd:integer[>= R])

Why a union and not one restriction per skill: a JD that says "熟练使用ERP订单管理模块及Excel数据分析"
is naming the tools the job uses, not demanding that one person hold every one of them. Requiring all of
them measured on the client's data: 业务跟单 matched 1 candidate out of 277, 副总助理 matched 0 — a
definition that is technically correct and commercially useless. `someValuesFrom` over a union says
"holds at least one of the skills this role is built around", which is what a shortlist means. Categories are emitted from the same vocabulary the
ABox builder types individuals with, so the two sides cannot drift — the first spike hand-wrote six and
typo'd `:CAD` as `:CAT`, and every AutoCAD requirement silently matched nobody.

Everything the JD did NOT state is written into `:notStated` on the role individual and into the report,
never into a default: a role with no stated floor cannot claim to match on one.

The `reasoning.json` expectations are computed by a SECOND route — plain Python over the records, no
reasoner — so `check_abox` compares two derivations rather than trusting the one it is testing.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))

from scripts.talent.build_abox import SKILL_CATEGORY, _local_id  # noqa: E402
from scripts.talent.jd_parse import EDUCATION_RANK  # noqa: E402

#: A role the dossier has CVs for but no job description: it must become a declared hole, not a guess.
_UNMATCHED_ROLE_NOTE = "no 职务说明书 for this role: the floor is unstated, so no match class is defined"


def _skill_of(requirements: list[dict]) -> dict[str, str]:
    """skill -> category, defaulting to a per-skill category when the vocabulary has none."""
    out = dict(SKILL_CATEGORY)
    for req in requirements:
        for skill in req.get("skills") or []:
            out.setdefault(skill, _local_id(skill, "Cat"))
    return out


def _class_name(role: str) -> str:
    return _local_id(role, "matches")


def _group_name(role: str) -> str:
    return _local_id(role, "skillsFor")


def build_tbox(requirements: list[dict], ns: str) -> tuple[str, dict]:
    categories = sorted(set(_skill_of(requirements).values()))
    definitions: dict[str, dict] = {}
    lines = [
        "# Role axioms generated by scripts/talent/author_tbox.py from the client's job descriptions.",
        "# A role becomes a DEFINED class: nobody types a candidate with it, the reasoner entails it.",
        "@prefix : <{{NS}}> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
        ":Candidate a owl:Class .",
        ":Role a owl:Class ; owl:disjointWith :Candidate .",
        ":SkillTag a owl:Class .",
        "",
        ":hasSkill a owl:ObjectProperty ; rdfs:domain :Candidate ; rdfs:range :SkillTag .",
        ":yearsExperience a owl:DatatypeProperty ; rdfs:domain :Candidate ; rdfs:range xsd:integer .",
        ":educationRank a owl:DatatypeProperty ; rdfs:domain :Candidate ; rdfs:range xsd:integer .",
        ":appliedFor a owl:ObjectProperty ; rdfs:domain :Candidate ; rdfs:range :Role .",
        ":missingData a owl:ObjectProperty ; rdfs:domain :Candidate .",
        ":salaryMinK a owl:DatatypeProperty ; rdfs:domain :Candidate ; rdfs:range xsd:integer .",
        ":salaryMaxK a owl:DatatypeProperty ; rdfs:domain :Candidate ; rdfs:range xsd:integer .",
        ":age a owl:DatatypeProperty ; rdfs:domain :Candidate ; rdfs:range xsd:integer .",
        ":sourceFile a owl:DatatypeProperty ; rdfs:domain :Candidate ; rdfs:range xsd:string .",
        ":requiredYears a owl:DatatypeProperty ; rdfs:domain :Role ; rdfs:range xsd:integer .",
        ":requiredEducationRank a owl:DatatypeProperty ; rdfs:domain :Role ; rdfs:range xsd:integer .",
        ":requiresSkill a owl:ObjectProperty ; rdfs:domain :Role ; rdfs:range :SkillTag .",
        ":notStated a owl:DatatypeProperty ; rdfs:domain :Role ; rdfs:range xsd:string .",
        "",
        "# ── skill categories (generated from the vocabulary the ABox types individuals with)",
    ]
    for category in categories:
        lines.append(f":{category} a owl:Class ; rdfs:subClassOf :SkillTag .")
    lines.append("")
    lines.append("# ── role definitions, one per job description that stated enough to judge")

    for req in requirements:
        role = req["role"]
        skills = req.get("skills") or []
        years = req.get("min_years")
        rank = req.get("education_rank")
        if not skills or years is None:
            definitions[role] = {"defined": False,
                                 "why": "the JD states no "
                                        + ("required skill" if not skills else "minimum years")}
            continue
        cls = _class_name(role)
        group = _group_name(role)
        categories_of_role = sorted({_skill_of(requirements)[s] for s in skills})
        # Inside an RDF list the members are SPACE-separated; `⊔` is the mathematical symbol and is
        # not Turtle (the first generated ABox died with "expected item in list or ')'").
        union = " ".join(f":{c}" for c in categories_of_role)
        restrictions = ["        :Candidate",
                        f"        [ a owl:Restriction ; owl:onProperty :hasSkill ; "
                        f"owl:someValuesFrom :{group} ]"]
        restrictions.append(
            f"        [ a owl:Restriction ; owl:onProperty :yearsExperience ;\n"
            f"          owl:someValuesFrom [ a rdfs:Datatype ; owl:onDatatype xsd:integer ;\n"
            f"                               owl:withRestrictions ( [ xsd:minInclusive {int(years)} ] ) ] ]")
        if rank:
            restrictions.append(
                f"        [ a owl:Restriction ; owl:onProperty :educationRank ;\n"
                f"          owl:someValuesFrom [ a rdfs:Datatype ; owl:onDatatype xsd:integer ;\n"
                f"                               owl:withRestrictions ( [ xsd:minInclusive {int(rank)} ] ) ] ]")
        joined = "\n".join(restrictions)
        lines += [
            "",
            f"# {role}: any of {skills} -> categories {categories_of_role}; years>={years}"
            + (f" education>={req['education_floor']}" if rank else " education: NOT STATED")
            + (f" · NOT STATED: {req['missing']}" if req.get("missing") else ""),
            f":{group} a owl:Class ; rdfs:subClassOf :SkillTag ;",
            f"    owl:equivalentClass [ owl:unionOf ( {union} ) ] .",
            f":{cls} a owl:Class ;",
            f"    rdfs:label {json.dumps(cls + ' (' + role + ')', ensure_ascii=False)} ;",
            "    owl:equivalentClass [ owl:intersectionOf (",
            joined,
            "    ) ] .",
        ]
        definitions[role] = {"class": cls, "defined": True, "skills": skills,
                             "years": int(years), "education_rank": rank,
                             "missing": req.get("missing") or []}
    return "\n".join(lines) + "\n", {"definitions": definitions, "categories": categories}


def second_route(records: list[dict], *, skills: list[str], years: int,
                 education_rank: int | None) -> set[str]:
    """The expectation, computed WITHOUT the reasoner: plain Python over the records."""
    out = set()
    for rec in records:
        stated_years = (rec.get("years_experience") or {}).get("value")
        if stated_years is None or int(stated_years) < years:
            continue
        stated = set(rec.get("skills") or [])
        if not stated.intersection(skills):  # ANY of the role's skills, mirroring the union axiom
            continue
        if education_rank is not None:
            rank = EDUCATION_RANK.get(((rec.get("education") or {}).get("value") or ""), None)
            if rank is None or rank < education_rank:
                continue
        out.add(rec["candidate_id"])
    return out


def build_spec(records: list[dict], tbox: dict, ns: str) -> dict:
    inferred, excluded, falsify = [], [], []
    for role, info in tbox["definitions"].items():
        if not info["defined"]:
            continue
        members = second_route(records, skills=info["skills"], years=info["years"],
                               education_rank=info["education_rank"])
        cls = info["class"]
        inferred.append({
            "class": cls,
            "members": sorted(_local_id(m, "cand") for m in sorted(members)[:5]),
            "why": f"second route: skills {info['skills']} + years >= {info['years']}"
                   + (f" + education rank >= {info['education_rank']}" if info["education_rank"] else "")
                   + f" gives {len(members)} of {len(records)} candidates",
        })
        non = [r["candidate_id"] for r in records
               if r["candidate_id"] not in members
               and (r.get("years_experience") or {}).get("value") is not None][:3]
        excluded.append({"class": cls,
                         "individuals": sorted(_local_id(m, "cand") for m in non),
                         "why": "the second route says these miss a skill, a year or the floor"})
        falsify.append({"label": f"drop the definition of {cls}",
                        "drop": {"subject": cls, "predicate": "equivalentClass"},
                        "class": cls,
                        "then_excluded": sorted(_local_id(m, "cand") for m in sorted(members)[:2])})
        if members:
            who = sorted(members)[0]
            falsify.append({"label": f"drop {who}'s skill assertions",
                            "drop": {"subject": _local_id(who, "cand"), "predicate": "hasSkill"},
                            "class": cls, "then_excluded": [_local_id(who, "cand")]})
    return {
        "reasoner": "hermit",
        "inferred": inferred,
        "excluded": excluded,
        "falsify": falsify[:24],
        "consistency": {"must_be_consistent": True},
        "coverage": {
            "source_files": len(records),
            "loaded_individuals": len(records),
            "required_props": [
                {"class": "Candidate", "prop": "appliedFor"},
                {"class": "Candidate", "prop": "hasSkill", "unless_marked": "UnknownSkills"},
            ],
        },
        "pii": {"patterns": [r"\b1[3-9]\d{9}\b", r"[\w.+-]+@[\w-]+\.[\w.]+"]},
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidates", required=True)
    ap.add_argument("--requirements", required=True)
    ap.add_argument("--out-dir", required=True, help="where reasoning.ttl / reasoning.json go")
    ap.add_argument("--key", default="talent_v1")
    ap.add_argument("--ns", default="")
    args = ap.parse_args()

    ns = (args.ns or f"https://cube.local/ontology/{args.key}#")
    records = [json.loads(line) for line in
               pathlib.Path(args.candidates).read_text(encoding="utf-8").splitlines() if line.strip()]
    requirements = json.loads(pathlib.Path(args.requirements).read_text(encoding="utf-8"))

    turtle, tbox = build_tbox(requirements, ns)
    spec = build_spec(records, tbox, ns)

    out = pathlib.Path(args.out_dir).expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / "reasoning.ttl").write_text(turtle.replace("{{NS}}", ns), encoding="utf-8")
    (out / "reasoning.json").write_text(json.dumps(spec, ensure_ascii=False, indent=1) + "\n",
                                        encoding="utf-8")

    print(f"wrote {out}/reasoning.ttl and reasoning.json")
    defined = [(r, i) for r, i in tbox["definitions"].items() if i["defined"]]
    undefined = [(r, i) for r, i in tbox["definitions"].items() if not i["defined"]]
    print(f"  role definitions : {len(defined)} of {len(tbox['definitions'])} roles")
    for role, info in defined:
        members = second_route(records, skills=info["skills"], years=info["years"],
                               education_rank=info["education_rank"])
        print(f"    {role:10s} -> {info['class']:26s} {len(members):4d} candidate(s) by the second route")
    if undefined:
        print(f"  NOT DEFINED (the JD states too little to judge; a declared hole, not a guess):")
        for role, info in undefined:
            print(f"    {role:10s} {info['why']}")
    roles_with_cvs = {}
    for rec in records:
        role = (rec.get("role_folder") or {}).get("value")
        if role:
            roles_with_cvs[role] = roles_with_cvs.get(role, 0) + 1
    missing_jd = sorted(r for r in roles_with_cvs if r not in tbox["definitions"])
    if missing_jd:
        print("  CVs with NO job description (no definition possible, must be a declared hole):")
        for role in missing_jd:
            print(f"    {role:10s} {roles_with_cvs[role]:3d} CV(s) — {_UNMATCHED_ROLE_NOTE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
