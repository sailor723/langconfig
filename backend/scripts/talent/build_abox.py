#!/usr/bin/env python3
"""Turn candidate records into an ABox — assertions only, and no invented values.

Input: the JSONL `extract.py` wrote (one record per CV scan) and, optionally, `requirements.json`
(`jd.py`) so role individuals carry the client's stated floor.

Output: `abox.ttl` in the profile layout `check_abox.py` expects. What it asserts, and why:

  :Candidate           one individual per CV, named from the file so a reviewer can trace any answer
                       back to the scan it came from
  :hasSkill            only skills the OCR actually matched, each typed into its CATEGORY class
                       (`:skill_SolidWorks a :CAD`) — the taxonomy lives in the TBox, this file only
                       says which individual belongs to which category
  :yearsExperience     ONLY when a source stated it. A candidate with no stated years gets
                       `:missingData :UnknownYears` instead of a zero
  :educationRank       2 中专/高中 · 3 大专 · 4 本科 · 5 硕士 · 6 博士, from the OCRed education line;
                       nobody gets a rank nobody stated
  :appliedFor          the role the recruiting platform filed them under (folder or file name)
  :sameAs              the 7 duplicate scans, so a per-role count is not inflated
  :sourceFile          the path, for auditability — not the person's name

The TBox is NOT written here: role definitions are a statement about the business ("2 years of order
tracking experience and ERP"), and that belongs to whoever owns the ontology, in `reasoning.ttl`.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))

from scripts.talent.jd_parse import EDUCATION_RANK  # noqa: E402

#: canonical skill -> the category class it is an instance of (the TBox declares the categories)
SKILL_CATEGORY = {
    "SolidWorks": "CAD", "AutoCAD": "CAD", "ProE/Creo": "CAD", "CATIA": "CAD", "UG/NX": "CAD",
    "Rhino": "CAD", "KeyShot": "CAD",
    "Photoshop": "DesignSoftware", "Illustrator": "DesignSoftware", "CorelDRAW": "DesignSoftware",
    "Excel": "SpreadsheetSoftware", "Word": "OfficeSoftware", "PowerPoint": "OfficeSoftware",
    "ERP": "BusinessSystem", "SAP": "BusinessSystem",
    "英语": "LanguageSkill",
    "外贸业务": "TradeSkill", "跟单": "OrderTracking", "报关": "CustomsSkill", "单证": "CustomsSkill",
    "招聘": "RecruitingSkill", "薪酬绩效": "CompensationSkill", "劳动法": "LaborLawKnowledge",
    "行政": "AdminSkill", "财务": "FinanceSkill",
    "ISO9001": "QualitySystem", "ISO/TS16949": "QualitySystem",
    "精益生产": "OperationsSkill", "5S": "OperationsSkill",
}

SAFE = re.compile(r"[^0-9A-Za-z_\u4e00-\u9fa5]+")


def _local_id(text: str, prefix: str) -> str:
    """A stable Turtle-safe local name; CJK is legal in Turtle, punctuation is not."""
    cleaned = SAFE.sub("_", text).strip("_")
    return f"{prefix}_{cleaned[:60]}"


def _lit(text: str) -> str:
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(records: list[dict], requirements: list[dict] | None = None) -> tuple[str, dict]:
    """(turtle, stats). Stats is what the gate's coverage block is written from."""
    roles_seen: dict[str, int] = {}
    skill_individuals: dict[str, str] = {}
    stats = {"candidates": 0, "with_years": 0, "with_education": 0, "with_skills": 0,
             "unknown_years": 0, "unknown_education": 0, "unknown_skills": 0,
             "duplicates": 0, "roles": {}}

    lines: list[str] = [
        "# ABox generated by scripts/talent/build_abox.py — assertions only.",
        "# Every value here came from a path, a file name or OCR; nothing was inferred.",
        "@prefix : <{{NS}}> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
        "# ── the two unknown markers: absence is recorded, never defaulted to 0",
        ":UnknownYears a owl:NamedIndividual ; rdfs:label \"工作年限未声明\" .",
        ":UnknownEducation a owl:NamedIndividual ; rdfs:label \"学历未读到\" .",
        ":UnknownSkills a owl:NamedIndividual ; rdfs:label \"技能未识别\" .",
        "",
    ]

    for rec in records:
        cid = _local_id(rec["candidate_id"], "cand")
        role = (rec.get("role_folder") or {}).get("value") or (rec.get("applied_role") or {}).get("value")
        lines.append(f":{cid} a :Candidate ;")
        if role:
            role_id = _local_id(role, "role")
            roles_seen[role] = roles_seen.get(role, 0) + 1
            lines.append(f"    :appliedFor :{role_id} ;")
        years = (rec.get("years_experience") or {}).get("value")
        if years is None:
            lines.append("    :missingData :UnknownYears ;")
            stats["unknown_years"] += 1
        else:
            lines.append(f"    :yearsExperience {int(years)} ;")
            stats["with_years"] += 1
        edu = (rec.get("education") or {}).get("value")
        rank = EDUCATION_RANK.get(edu or "")
        if rank is None:
            lines.append("    :missingData :UnknownEducation ;")
            stats["unknown_education"] += 1
        else:
            lines.append(f"    :educationRank {int(rank)} ;")
            stats["with_education"] += 1
        if not rec.get("skills"):
            # A candidate whose OCR text named no recognisable skill is MARKED. Leaving the property
            # off would look identical to "has no skills", and the gate cannot tell a gap from a fact.
            lines.append("    :missingData :UnknownSkills ;")
            stats["unknown_skills"] = stats.get("unknown_skills", 0) + 1
        for skill in rec.get("skills") or []:
            skill_id = _local_id(skill, "skill")
            skill_individuals[skill] = skill_id
            lines.append(f"    :hasSkill :{skill_id} ;")
        if rec.get("skills"):
            stats["with_skills"] += 1
        for key, prop in (("salary_min_k", ":salaryMinK"), ("salary_max_k", ":salaryMaxK"),
                          ("age", ":age")):
            value = (rec.get(key) or {}).get("value")
            if value is not None:
                lines.append(f"    {prop} {int(value)} ;")
        if rec.get("duplicate_of"):
            dup_id = _local_id(pathlib.Path(rec["duplicate_of"]).stem, "cand")
            # `owl:sameAs`, not a local `:sameAs`: the standard predicate is what every consumer
            # (materialise, the sync gate, a future reasoner run) looks for, and a local one measured
            # as "0 duplicates" while seven pairs sat in the ABox.
            lines.append(f"    owl:sameAs :{dup_id} ;")
            stats["duplicates"] += 1
        lines.append(f"    :sourceFile {_lit(rec['source_file'])} .")
        lines.append("")
        stats["candidates"] += 1

    # A skill the JOB requires but nobody lists is exactly the gap a shortlist must be able to show,
    # so requirement-side skills become individuals too. Without this the role's `:requiresSkill`
    # pointed at an undeclared individual, its category was unknown, and the fit table scored every
    # such role with "0 of 0 skills" — a perfect-looking row that measured nothing.
    if requirements:
        for req in requirements:
            for skill in req.get("skills") or []:
                skill_individuals.setdefault(skill, _local_id(skill, "skill"))

    lines.append("# ── skills: individuals, each typed into the category the TBox reasons over")
    for skill, skill_id in sorted(skill_individuals.items()):
        category = SKILL_CATEGORY.get(skill)
        types = f"a :{category}, :SkillTag" if category else "a :SkillTag"
        label = f' ; rdfs:label {_lit(skill)}' if skill != skill_id else ""
        lines.append(f":{skill_id} {types}{label} .")
    lines.append("")

    if requirements:
        lines.append("# ── roles and what the client's job description states for them")
        for req in requirements:
            role_id = _local_id(req["role"], "role")
            bits = [f":{role_id} a :Role", f"rdfs:label {_lit(req['role'])}"]
            if req.get("education_rank"):
                bits.append(f":requiredEducationRank {int(req['education_rank'])}")
            if req.get("min_years") is not None:
                bits.append(f":requiredYears {int(req['min_years'])}")
            for skill in req.get("skills") or []:
                skill_id = skill_individuals.get(skill) or _local_id(skill, "skill")
                bits.append(f":requiresSkill :{skill_id}")
            if req.get("missing"):
                bits.append(f':notStated {_lit(",".join(req["missing"]))}')
            lines.append(" ;\n    ".join(bits) + " .")
        lines.append("")

    stats["roles"] = roles_seen
    stats["skills"] = sorted(skill_individuals)
    return "\n".join(lines), stats


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidates", required=True, help="JSONL from extract.py")
    ap.add_argument("--requirements", default="", help="JSON from jd.py (optional)")
    ap.add_argument("--out", required=True, help="abox.ttl to write")
    ap.add_argument("--ns", default="https://cube.local/ontology/talent_v1#")
    ap.add_argument("--limit", type=int, default=0)
    args = ap.parse_args()

    rows = [json.loads(line) for line in pathlib.Path(args.candidates).read_text(encoding="utf-8")
            .splitlines() if line.strip()]
    if args.limit:
        rows = rows[: args.limit]
    reqs = (json.loads(pathlib.Path(args.requirements).read_text(encoding="utf-8"))
            if args.requirements else None)

    turtle, stats = build(rows, reqs)
    turtle = turtle.replace("{{NS}}", args.ns)
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(turtle, encoding="utf-8")

    print(f"wrote {out} ({len(turtle)} chars)")
    print(f"  candidates        : {stats['candidates']}")
    print(f"  years stated      : {stats['with_years']}  (unknown recorded: {stats['unknown_years']})")
    print(f"  education stated  : {stats['with_education']}  (unknown: {stats['unknown_education']})")
    print(f"  with >=1 skill    : {stats['with_skills']}  (unknown recorded: {stats['unknown_skills']})")
    print(f"  duplicates linked : {stats['duplicates']}")
    print(f"  skills            : {len(stats['skills'])} distinct")
    print(f"  roles             : {len(stats['roles'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
