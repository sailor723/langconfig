"""
LangConfig Setup Script
=======================

One-command setup for fresh clones. Handles:
1. Environment file generation (.env — Postgres bootstrap + generated encryption key)
2. Python dependency installation
3. Database initialization (tables + extensions)
4. Playwright browser installation (optional)

Usage:
    python scripts/setup.py           # Full setup
    python scripts/setup.py --db-only # Database only
    python scripts/setup.py --help    # Show help
"""

import os
import sys
import shutil
import subprocess
import argparse
from pathlib import Path

# Colors for terminal output
class Colors:
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    RED = '\033[91m'
    BLUE = '\033[94m'
    RESET = '\033[0m'
    BOLD = '\033[1m'

def print_step(msg: str):
    print(f"\n{Colors.BLUE}{Colors.BOLD}==>{Colors.RESET} {msg}")

def print_success(msg: str):
    print(f"  {Colors.GREEN}✓{Colors.RESET} {msg}")

def print_warning(msg: str):
    print(f"  {Colors.YELLOW}⚠{Colors.RESET} {msg}")

def print_error(msg: str):
    print(f"  {Colors.RED}✗{Colors.RESET} {msg}")

def get_project_root() -> Path:
    """Get the project root directory."""
    # This script is in backend/scripts/, so go up two levels
    return Path(__file__).parent.parent.parent

def check_python_version():
    """Ensure Python 3.11+ is being used."""
    print_step("Checking Python version...")
    version = sys.version_info
    if version.major < 3 or (version.major == 3 and version.minor < 11):
        print_error(f"Python 3.11+ required, found {version.major}.{version.minor}")
        print_warning("Install Python 3.11+ from https://python.org")
        return False
    print_success(f"Python {version.major}.{version.minor}.{version.micro}")
    return True

def check_docker():
    """Check if Docker is available."""
    print_step("Checking Docker...")
    try:
        result = subprocess.run(
            ["docker", "--version"],
            capture_output=True, text=True, check=True
        )
        print_success(f"Docker found: {result.stdout.strip()}")
        return True
    except (subprocess.CalledProcessError, FileNotFoundError):
        print_warning("Docker not found - you'll need to set up PostgreSQL manually")
        return False

def setup_env_file():
    """Generate a minimal .env if it doesn't exist (Phase 5b).

    Only the Postgres bootstrap + the Fernet encryption key are required;
    everything user-facing lives in PostgreSQL settings documents (seeded on
    first boot) and API keys are entered in the first-run wizard / Settings.
    A random encryption key is generated when none is provided.
    """
    print_step("Setting up environment file...")
    root = get_project_root()
    env_file = root / ".env"

    if env_file.exists():
        print_success(".env already exists")
        return True

    import secrets
    key = secrets.token_hex(32)
    lines = [
        "# LangConfig .env — minimal (generated by setup.py)",
        "#",
        "# REQUIRED: Postgres bootstrap + Fernet encryption key. All user-facing",
        "# settings (LLM defaults, workspace, storage, RAG, API keys, search keys)",
        "# live in PostgreSQL settings documents, seeded on first boot and",
        "# editable in Settings — no .env keys needed.",
        "#",
        f"API_KEY_ENCRYPTION_KEY={key}",
        "ENVIRONMENT=development",
        "",
        "POSTGRES_HOST=localhost",
        "POSTGRES_PORT=5432",
        "POSTGRES_DB=langconfig",
        "POSTGRES_USER=langconfig",
        "POSTGRES_PASSWORD=langconfig_dev",
        "",
    ]
    env_file.write_text("\n".join(lines))
    print_success("Created .env (Postgres bootstrap + generated encryption key)")
    print_warning("API keys are entered in the first-run wizard / Settings → Models (stored encrypted in PostgreSQL).")
    return True

def install_dependencies():
    """Install Python dependencies."""
    print_step("Installing Python dependencies...")
    root = get_project_root()
    requirements = root / "backend" / "requirements.txt"
    
    if not requirements.exists():
        print_error("requirements.txt not found!")
        return False
    
    try:
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "-r", str(requirements)],
            check=True
        )
        print_success("Dependencies installed")
        return True
    except subprocess.CalledProcessError as e:
        print_error(f"Failed to install dependencies: {e}")
        return False

def start_database():
    """Start PostgreSQL via Docker Compose."""
    print_step("Starting PostgreSQL database...")
    root = get_project_root()
    
    try:
        subprocess.run(
            ["docker", "compose", "up", "-d", "postgres"],
            cwd=root, check=True
        )
        print_success("PostgreSQL container started")
        
        # Wait for database to be ready
        print("  Waiting for database to be ready...")
        import time
        for i in range(30):
            try:
                result = subprocess.run(
                    ["docker", "compose", "exec", "-T", "postgres", 
                     "pg_isready", "-U", "langconfig"],
                    cwd=root, capture_output=True, check=True
                )
                print_success("Database is ready")
                return True
            except subprocess.CalledProcessError:
                time.sleep(1)
        
        print_warning("Database may not be fully ready yet")
        return True
    except subprocess.CalledProcessError as e:
        print_error(f"Failed to start database: {e}")
        return False
    except FileNotFoundError:
        print_warning("Docker not available - skipping container start")
        return True

def init_database():
    """Initialize the database via the canonical bootstrap (scripts/seeds/seed_all.py).

    Delegates to seed_all.py so there is exactly one install path: it creates
    the role/database if missing, creates all tables + extensions, stamps the
    alembic version (no destructive DROP SCHEMA, no stale 006 stamp), and
    seeds models, search providers, tools, deep agents, skills, and settings
    documents. Idempotent — safe to re-run.
    """
    print_step("Initializing database (seed_all)...")

    root = get_project_root()
    backend_path = root / "backend"
    seed_script = backend_path / "scripts" / "seeds" / "seed_all.py"

    if not seed_script.exists():
        print_error(f"seed_all.py not found at {seed_script}")
        return False

    try:
        subprocess.run(
            [sys.executable, str(seed_script)],
            cwd=backend_path, check=True
        )
        print_success("Database initialized and seeded (tables + models + tools + agents + skills + settings)")
        return True
    except subprocess.CalledProcessError as e:
        print_error(f"Database initialization failed: {e}")
        return False
    except FileNotFoundError as e:
        print_error(f"Database initialization failed: {e}")
        return False

def install_playwright():
    """Install Playwright browsers (optional)."""
    print_step("Installing Playwright browsers (for browser automation tools)...")
    
    try:
        subprocess.run(
            [sys.executable, "-m", "playwright", "install", "chromium"],
            check=True
        )
        print_success("Playwright Chromium installed")
        return True
    except subprocess.CalledProcessError as e:
        print_warning(f"Playwright install failed (optional): {e}")
        return True  # Non-fatal
    except FileNotFoundError:
        print_warning("Playwright not found - browser tools will be unavailable")
        return True  # Non-fatal

def seed_agent_templates():
    """Seed default agent templates."""
    print_step("Seeding agent templates...")

    root = get_project_root()
    backend_path = root / "backend"
    init_script = backend_path / "db" / "init_deepagents.py"

    if not init_script.exists():
        print_warning("Agent template seed script not found - skipping")
        return True

    try:
        subprocess.run(
            [sys.executable, str(init_script)],
            cwd=backend_path, check=True
        )
        print_success("Agent templates seeded")
        return True
    except subprocess.CalledProcessError as e:
        print_warning(f"Template seeding failed (non-fatal): {e}")
        return True

def seed_custom_tools():
    """Seed default custom tools (Nano Banana, etc.)."""
    print_step("Seeding custom tools...")

    root = get_project_root()
    backend_path = root / "backend"
    init_script = backend_path / "db" / "init_custom_tools.py"

    if not init_script.exists():
        print_warning("Custom tool seed script not found - skipping")
        return True

    try:
        subprocess.run(
            [sys.executable, str(init_script)],
            cwd=backend_path, check=True
        )
        print_success("Custom tools seeded (Nano Banana Pro, etc.)")
        return True
    except subprocess.CalledProcessError as e:
        print_warning(f"Custom tool seeding failed (non-fatal): {e}")
        return True

def print_next_steps():
    """Print instructions for what to do next."""
    print(f"\n{Colors.GREEN}{Colors.BOLD}Setup Complete!{Colors.RESET}\n")
    print("Next steps:")
    print(f"  1. Start the backend:")
    print(f"     {Colors.BOLD}cd backend && python -m uvicorn main:app --reload --port 8765{Colors.RESET}")
    print()
    print(f"  2. Start the frontend (in another terminal):")
    print(f"     {Colors.BOLD}npm install && npm run dev{Colors.RESET}")
    print()
    print(f"  3. Open {Colors.BOLD}http://localhost:1421{Colors.RESET} in your browser")
    print()
    print(f"  4. First-run wizard: enter your API key + workspace path")
    print(f"     (or use Settings > Models later). Keys are stored encrypted")
    print(f"     in PostgreSQL — no more editing .env for API keys.")
    print()

def main():
    parser = argparse.ArgumentParser(
        description="LangConfig setup script for fresh installations"
    )
    parser.add_argument(
        "--db-only", action="store_true",
        help="Only initialize the database (skip deps install)"
    )
    parser.add_argument(
        "--skip-docker", action="store_true",
        help="Skip Docker container startup (use existing database)"
    )
    parser.add_argument(
        "--skip-playwright", action="store_true",
        help="Skip Playwright browser installation"
    )
    args = parser.parse_args()
    
    print(f"\n{Colors.BOLD}LangConfig Setup{Colors.RESET}")
    print("=" * 40)
    
    # Change to backend directory
    root = get_project_root()
    os.chdir(root / "backend")
    
    success = True
    
    # Python version check
    if not check_python_version():
        sys.exit(1)
    
    if not args.db_only:
        # Environment file
        if not setup_env_file():
            success = False
        
        # Dependencies
        if not install_dependencies():
            success = False
    
    # Docker check
    has_docker = check_docker()
    
    # Start database
    if has_docker and not args.skip_docker:
        if not start_database():
            success = False
    
    # Initialize database
    if not init_database():
        success = False
    
    # Seed templates
    seed_agent_templates()

    # Seed custom tools
    seed_custom_tools()

    # Playwright (optional)
    if not args.db_only and not args.skip_playwright:
        install_playwright()
    
    if success:
        print_next_steps()
    else:
        print(f"\n{Colors.RED}Setup completed with errors. Check the output above.{Colors.RESET}")
        sys.exit(1)

if __name__ == "__main__":
    main()
