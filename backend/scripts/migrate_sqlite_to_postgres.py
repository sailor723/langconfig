#!/usr/bin/env python3
"""Move a SQLite database into PostgreSQL, types and keys included — with a check that says whether it landed.

Why this exists next to `load_workbook_to_postgres.py`: that tool starts from a spreadsheet and has to
GUESS types; a SQLite file already declares them, so the job here is faithful translation plus proof.
The proof matters more than the copy: a migrated KPI database whose numbers moved by a cent still renders
a dashboard, and nobody notices until someone asks why two reports disagree.

Type mapping (SQLite's declared type → PostgreSQL):

    INTEGER PRIMARY KEY AUTOINCREMENT → bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
    INTEGER PRIMARY KEY               → bigint PRIMARY KEY            (the values are the identity)
    TEXT/other PRIMARY KEY            → text PRIMARY KEY              (e.g. period 'YYYY-MM', kpi_id)
    INTEGER / BOOLEAN / numeric etc.  → bigint / boolean / numeric    (declared affinity decides)
    REAL / FLOAT / DOUBLE             → numeric                       (exact as written, not float drift)
    TEXT / CLOB / empty               → text

`period` stays TEXT on purpose: the KPI formulas compare it with `= ?` against 'YYYY-MM' strings, so a
DATE column would break every formula in `dim_kpi.formula` on the way over. A typed view can be added
later; the migration should not silently change what a string means.

The connection defaults to the platform's own server (POSTGRES_HOST/PORT/USER and PGPASSWORD or
POSTGRES_PASSWORD from the environment); pass --host/--port only to target a different server.

Usage:
    # into a database that must not exist yet (created here), or recreate it
    python backend/scripts/migrate_sqlite_to_postgres.py \
        --source /path/sunhing_kpi.db --dbname sunhing_kpi [--recreate]

    # verify only (no writes): compare row counts and numeric sums with the source
    python backend/scripts/migrate_sqlite_to_postgres.py --source … --dbname sunhing_kpi --verify-only
"""
from __future__ import annotations

import argparse
import os
import pathlib
import sqlite3
import sys
from pathlib import Path

import psycopg2
from psycopg2.extras import execute_values

#: SQLite's type affinity, resolved in this order (the first token wins).
_INT = ("INT", "BIGINT", "SMALLINT", "TINYINT", "MEDIUMINT", "BOOLEAN", "BOOL")
_REAL = ("REAL", "FLOA", "DOUB", "NUMERIC", "DECIMAL")
_TEXT = ("TEXT", "CHAR", "CLOB", "VARCHAR", "DATE", "DATETIME", "TIMESTAMP", "TIME", "JSON", "BLOB")



def _deployment_env() -> dict:
    """POSTGRES_* from the repo's single `.env`, then the process environment.

    The app loads `.env` through pydantic-settings, which does NOT put those names in `os.environ` — so a
    child process (an agent's `execute`, this script) saw no POSTGRES_* at all and had to be told the
    password on the command line. Measured on the first real run of the migration agent: it exported
    `PGPASSWORD=<password>` in a shell command, which puts the credential in the transcript. Reading the
    same `.env` the service reads removes the reason to do that.
    """
    out: dict[str, str] = {}
    env_file = pathlib.Path(__file__).resolve().parents[2] / ".env"
    if env_file.is_file():
        for raw in env_file.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, _, v = line.partition("=")
            k = k.strip()
            if k.startswith(("POSTGRES_", "PG")):
                out[k] = v.strip().strip('"').strip("'")
    for k, v in os.environ.items():
        # A bare `PGPORT` in the developer's shell belongs to a DIFFERENT server (this machine has a
        # Homebrew PostgreSQL on 5432 beside the app's on 5433). The deployment's own POSTGRES_* wins;
        # PGPASSWORD is still honoured because that is what an agent's sandbox exports for ITS database.
        if k == "PGPORT" and "POSTGRES_PORT" in out:
            continue
        if k == "PGDATABASE" and "POSTGRES_DB" in out:
            continue
        if k.startswith(("POSTGRES_", "PG")) and v:
            out[k] = v
    return out

def pg_type(declared: str) -> str:
    """The PostgreSQL type for a SQLite declared type (affinity rules, then a safe default)."""
    up = (declared or "").upper()
    if not up:
        return "text"
    for token in _INT:
        if token in up:
            return "boolean" if token in ("BOOLEAN", "BOOL") else "bigint"
    for token in _REAL:
        if token in up:
            return "numeric"
    for token in _TEXT:
        if token in up:
            return "text"
    return "text"


def introspect(src: sqlite3.Connection) -> list[dict]:
    """Every user table with its columns, declared types, primary key and autoincrement flag."""
    tables: list[dict] = []
    for (name,) in src.execute(
            "select name from sqlite_master where type='table' and name not like 'sqlite_%' order by name"):
        cols = []
        for cid, col, decl, notnull, default, pk in src.execute(f'pragma table_info("{name}")'):
            cols.append({"name": col, "declared": decl or "", "pg": pg_type(decl),
                         "notnull": bool(notnull), "pk": int(pk or 0), "default": default})
        # AUTOINCREMENT is not exposed by table_info: read it out of the SQL
        ddl = src.execute("select sql from sqlite_master where type='table' and name=?", (name,)).fetchone()[0]
        auto = "AUTOINCREMENT" in (ddl or "").upper()
        tables.append({"name": name, "cols": cols, "sqlite_ddl": ddl or "", "autoincrement": auto,
                       "rows": src.execute(f'select count(*) from "{name}"').fetchone()[0]})
    return tables


def ddl_for(table: dict) -> str:
    """CREATE TABLE with keys translated. Identifiers are quoted, so a column may be named anything."""
    name = table["name"]
    pk_cols = [c for c in table["cols"] if c["pk"]]
    single_int_pk = len(pk_cols) == 1 and pk_cols[0]["pg"] == "bigint"
    parts: list[str] = []
    for c in table["cols"]:
        col = f'    "{c["name"]}" {c["pg"]}'
        if c["notnull"]:
            col += " NOT NULL"
        if single_int_pk and c["pk"] and c["name"] == pk_cols[0]["name"] and table["autoincrement"]:
            col += " GENERATED BY DEFAULT AS IDENTITY"
        parts.append(col)
    if pk_cols:
        parts.append("    PRIMARY KEY (" + ", ".join(f'"{c["name"]}"' for c in pk_cols) + ")")
    return f'CREATE TABLE "{name}" (\n' + ",\n".join(parts) + "\n)"


def numeric_columns(table: dict) -> list[str]:
    return [c["name"] for c in table["cols"] if c["pg"] == "numeric"]


def connect_admin(args) -> psycopg2.extensions.connection:
    conn = psycopg2.connect(host=args.host, port=args.port, user=args.user, password=args.password,
                            dbname=args.maintenance_db)
    conn.autocommit = True
    return conn


def ensure_database(args) -> None:
    conn = connect_admin(args)
    try:
        with conn.cursor() as cur:
            cur.execute("select 1 from pg_database where datname = %s", (args.dbname,))
            exists = cur.fetchone() is not None
            if exists and not args.recreate:
                return
            if exists:
                cur.execute(f'DROP DATABASE "{args.dbname}" with (force)')
            cur.execute(f'CREATE DATABASE "{args.dbname}"')
            print(f"created database {args.dbname} on {args.host}:{args.port}")
    finally:
        conn.close()


def migrate(args) -> int:
    if not Path(args.source).is_file():
        print(f"no such file: {args.source}")
        return 2
    src = sqlite3.connect(f"file:{args.source}?mode=ro", uri=True)
    src.row_factory = sqlite3.Row
    tables = introspect(src)
    if not tables:
        print("the source has no tables")
        return 2

    if not args.verify_only:
        ensure_database(args)
    dst = psycopg2.connect(host=args.host, port=args.port, user=args.user, password=args.password,
                           dbname=args.dbname)
    dst.autocommit = False
    failures: list[str] = []
    try:
        with dst.cursor() as cur:
            if not args.verify_only:
                for plan in tables:
                    cur.execute(f'DROP TABLE IF EXISTS "{plan["name"]}" CASCADE')
                    cur.execute(ddl_for(plan))
                dst.commit()
                for plan in tables:
                    cols = [c["name"] for c in plan["cols"]]
                    rows = src.execute(
                        'select ' + ", ".join(f'"{c}"' for c in cols) + f' from "{plan["name"]}"').fetchall()
                    if rows:
                        payload = [tuple(r[c] for c in cols) for r in rows]
                        execute_values(
                            cur,
                            'INSERT INTO "' + plan["name"] + '" ('
                            + ", ".join(f'"{c}"' for c in cols) + ") VALUES %s",
                            payload, page_size=500)
                    dst.commit()
                    print(f'  copied {plan["name"]:<24} {len(rows):>5} row(s)')

            # ── verification: counts, then numeric sums (the thing a row count cannot see)
            print("\nverification")
            for plan in tables:
                name = plan["name"]
                cur.execute(f'select count(*) from "{name}"')
                got = cur.fetchone()[0]
                want = src.execute(f'select count(*) from "{name}"').fetchone()[0]
                ok = got == want
                print(f"  {'PASS' if ok else 'FAIL'} {name:<24} rows {got} vs {want}")
                if not ok:
                    failures.append(f"{name}: {got} rows in postgres, {want} in sqlite")
                    continue
                for col in numeric_columns(plan):
                    cur.execute(f'select coalesce(sum("{col}"), 0) from "{name}"')
                    pg_sum = cur.fetchone()[0]
                    s_sum = src.execute(f'select coalesce(sum("{col}"), 0) from "{name}"').fetchone()[0]
                    if abs(float(pg_sum or 0) - float(s_sum or 0)) > max(0.01, abs(float(s_sum or 0)) * 1e-9):
                        failures.append(f"{name}.{col}: sum {pg_sum} vs {s_sum}")
                        print(f"  FAIL {name}.{col} sum {pg_sum} vs {s_sum}")
    finally:
        dst.close()
        src.close()

    if failures:
        print("\nMIGRATION HAS DIFFERENCES:")
        for f in failures:
            print("  -", f)
        return 1
    print(f"\nOK — {len(tables)} table(s) migrated into {args.dbname} and every count and numeric sum agrees.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--source", required=True, help="the .db file")
    ap.add_argument("--dbname", required=True, help="target database (created unless it exists)")
    # Connection defaults come from the ENVIRONMENT, never from this file: a password literal in a
    # committed script is the same defect the ontology profiles were fixed for (gate X2), and on the
    # platform these names are already exported by the app's `.env` — `psql` in an agent's shell needs
    # no arguments, so the migration tool should not need them either.
    dep = _deployment_env()
    ap.add_argument("--host", default=dep.get("POSTGRES_HOST") or "localhost")
    ap.add_argument("--port", type=int, default=int(dep.get("POSTGRES_PORT") or 5432))
    ap.add_argument("--user", default=dep.get("POSTGRES_USER") or "postgres")
    ap.add_argument("--password",
                    default=dep.get("PGPASSWORD") or dep.get("POSTGRES_PASSWORD") or "",
                    help="prefer PGPASSWORD / POSTGRES_PASSWORD in the environment: an argument is visible "
                         "in the process list and in any transcript that quotes the command")
    ap.add_argument("--maintenance-db", default="postgres", help="database to connect through to CREATE the target")
    ap.add_argument("--recreate", action="store_true", help="drop and rebuild the target if it exists")
    ap.add_argument("--verify-only", action="store_true", help="compare with the source, write nothing")
    return migrate(ap.parse_args())


if __name__ == "__main__":
    sys.exit(main())
