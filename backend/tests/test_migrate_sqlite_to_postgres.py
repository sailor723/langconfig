"""The SQLite → PostgreSQL migration has to be faithful, and it has to say so.

A copy that silently changed a number would still render a dashboard: `REAL` → `double precision` drifts,
`INTEGER PRIMARY KEY AUTOINCREMENT` loses its identity, `TEXT` periods become dates and the KPI formulas
in `dim_kpi.formula` (which compare `period = ?` against 'YYYY-MM' strings) stop matching. So the tool
translates the declared types, then PROVES the copy: per-table row counts and per-numeric-column sums.

The round-trip test below builds a tiny SQLite file with exactly those hazards and compares it with the
PostgreSQL copy. It needs a reachable server; it skips elsewhere rather than pretending.
"""
import sqlite3
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "backend" / "scripts" / "migrate_sqlite_to_postgres.py"
sys.path.insert(0, str(REPO / "backend" / "scripts"))


def _reachable() -> bool:
    try:
        import psycopg2

        conn = psycopg2.connect(host="localhost", port=5433, user="langconfig",
                                password="langconfig_dev", dbname="postgres", connect_timeout=3)
        conn.close()
        return True
    except Exception:                                           # noqa: BLE001
        return False


# ── the type mapping (no server needed) ───────────────────────────────────

@pytest.mark.parametrize("declared,pg", [
    ("INTEGER", "bigint"),
    ("INT", "bigint"),
    ("BIGINT", "bigint"),
    ("BOOLEAN", "boolean"),
    ("REAL", "numeric"),
    ("DOUBLE", "numeric"),
    ("FLOAT", "numeric"),
    ("NUMERIC(10,2)", "numeric"),
    ("DECIMAL", "numeric"),
    ("TEXT", "text"),
    ("VARCHAR(30)", "text"),
    ("DATE", "text"),          # deliberately: `period` must stay a string, the KPI formulas bind 'YYYY-MM'
    ("", "text"),
    ("weird_type", "text"),
])
def test_type_mapping(declared, pg):
    from migrate_sqlite_to_postgres import pg_type

    assert pg_type(declared) == pg


def test_autoincrement_becomes_identity_and_a_text_pk_stays_a_pk():
    from migrate_sqlite_to_postgres import ddl_for

    table = {
        "name": "probe", "autoincrement": True,
        "cols": [
            {"name": "id", "declared": "INTEGER", "pg": "bigint", "notnull": True, "pk": 1},
            {"name": "period", "declared": "TEXT", "pg": "text", "notnull": True, "pk": 2},
            {"name": "amount_wan", "declared": "REAL", "pg": "numeric", "notnull": False, "pk": 0},
        ],
    }
    ddl = ddl_for(table)
    assert "GENERATED BY DEFAULT AS IDENTITY" not in ddl, "a composite key is not an identity column"
    assert 'PRIMARY KEY ("id", "period")' in ddl
    assert '"amount_wan" numeric' in ddl

    single = {
        "name": "raw_x", "autoincrement": True,
        "cols": [{"name": "id", "declared": "INTEGER", "pg": "bigint", "notnull": True, "pk": 1}],
    }
    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl_for(single)


def test_the_script_carries_no_literal_credential():
    """A password default in a committed script is the defect the ontology profiles were fixed for (X2)."""
    text = SCRIPT.read_text(encoding="utf-8")
    body = text[text.index("def main("):]
    assert 'default="langconfig' not in body
    # the credentials come from the deployment's own .env (and, for a sandbox, from PGPASSWORD) via one
    # helper — so the assertion is on where they are read, not on the exact expression
    assert "_deployment_env()" in body
    # the helper collects every POSTGRES_*/PG* name; the password one specifically is chosen in main(),
    # so assert it there (the helper's own prefix filter is what makes POSTGRES_PASSWORD reachable).
    assert 'dep.get("PGPASSWORD") or dep.get("POSTGRES_PASSWORD")' in body
    env_helper = text[text.index("def _deployment_env("):text.index("def pg_type(")]
    assert 'startswith(("POSTGRES_", "PG"))' in env_helper


# ── the round trip ───────────────────────────────────────────────────────

def test_a_hazardous_sqlite_file_survives_the_copy(tmp_path):
    if not _reachable():
        pytest.skip("no PostgreSQL server on localhost:5433 for this checkout")

    source = tmp_path / "probe.db"
    con = sqlite3.connect(source)
    con.executescript("""
        CREATE TABLE dim_probe (period TEXT PRIMARY KEY, label TEXT NOT NULL, ratio REAL, flag INTEGER);
        CREATE TABLE raw_probe (id INTEGER PRIMARY KEY AUTOINCREMENT, dim_period TEXT, amount_wan REAL);
        INSERT INTO dim_probe VALUES ('2026-11', '十一月 · 温控', 0.9459, 1);
        INSERT INTO dim_probe VALUES ('2026-12', '十二月', 1.0, 0);
        INSERT INTO raw_probe (dim_period, amount_wan) VALUES ('2026-11', 5678.125);
        INSERT INTO raw_probe (dim_period, amount_wan) VALUES ('2026-12', NULL);
    """)
    con.commit()
    con.close()

    dbname = "zz_migrate_probe"
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), "--source", str(source), "--dbname", dbname, "--recreate"],
        capture_output=True, text=True, timeout=180, cwd=str(REPO / "backend"))
    try:
        assert proc.returncode == 0, proc.stdout + proc.stderr
        assert "every count and numeric sum agrees" in proc.stdout

        import psycopg2

        pg = psycopg2.connect(host="localhost", port=5433, user="langconfig",
                              password="langconfig_dev", dbname=dbname)
        with pg.cursor() as cur:
            cur.execute("select period, label, ratio, flag from dim_probe order by period")
            rows = cur.fetchall()
            assert rows[0][0] == "2026-11", "the period string changed"
            assert "十一月" in rows[0][1], "utf-8 text did not survive"
            assert float(rows[0][2]) == 0.9459
            cur.execute("select amount_wan from raw_probe where amount_wan is not null")
            assert float(cur.fetchone()[0]) == 5678.125, "REAL drifted through the copy"
            cur.execute("select count(*) from raw_probe where amount_wan is null")
            assert cur.fetchone()[0] == 1, "a NULL became a 0"
            cur.execute("""select data_type from information_schema.columns
                           where table_name='raw_probe' and column_name='id'""")
            assert cur.fetchone()[0] == "bigint"
        pg.close()

        # verify-only must agree with a fresh copy and write nothing
        again = subprocess.run(
            [sys.executable, str(SCRIPT), "--source", str(source), "--dbname", dbname, "--verify-only"],
            capture_output=True, text=True, timeout=180, cwd=str(REPO / "backend"))
        assert again.returncode == 0, again.stdout + again.stderr
    finally:
        import psycopg2

        admin = psycopg2.connect(host="localhost", port=5433, user="langconfig",
                                 password="langconfig_dev", dbname="postgres")
        admin.autocommit = True
        with admin.cursor() as cur:
            cur.execute(f'DROP DATABASE IF EXISTS "{dbname}" with (force)')
        admin.close()


def test_the_tool_says_so_when_the_copy_disagrees(tmp_path):
    """A verification that cannot fail is decoration: break one row after the copy and re-check."""
    if not _reachable():
        pytest.skip("no PostgreSQL server on localhost:5433 for this checkout")
    source = tmp_path / "probe2.db"
    con = sqlite3.connect(source)
    con.executescript("CREATE TABLE t (id INTEGER PRIMARY KEY, amount REAL);"
                      "INSERT INTO t (id, amount) VALUES (1, 10.5), (2, 20.0);")
    con.commit()
    con.close()
    dbname = "zz_migrate_probe2"
    proc = subprocess.run([sys.executable, str(SCRIPT), "--source", str(source), "--dbname", dbname,
                           "--recreate"], capture_output=True, text=True, timeout=180,
                          cwd=str(REPO / "backend"))
    try:
        assert proc.returncode == 0, proc.stdout + proc.stderr
        import psycopg2

        pg = psycopg2.connect(host="localhost", port=5433, user="langconfig",
                              password="langconfig_dev", dbname=dbname)
        pg.autocommit = True
        with pg.cursor() as cur:
            cur.execute("update t set amount = 99 where id = 2")
        pg.close()
        check = subprocess.run([sys.executable, str(SCRIPT), "--source", str(source), "--dbname", dbname,
                                "--verify-only"], capture_output=True, text=True, timeout=180,
                               cwd=str(REPO / "backend"))
        assert check.returncode == 1, "a changed amount passed the verification"
        assert "MIGRATION HAS DIFFERENCES" in check.stdout
        assert "amount" in check.stdout
    finally:
        import psycopg2

        admin = psycopg2.connect(host="localhost", port=5433, user="langconfig",
                                 password="langconfig_dev", dbname="postgres")
        admin.autocommit = True
        with admin.cursor() as cur:
            cur.execute(f'DROP DATABASE IF EXISTS "{dbname}" with (force)')
        admin.close()
