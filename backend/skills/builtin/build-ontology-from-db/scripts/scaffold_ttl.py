#!/usr/bin/env python3
"""Phase 3: draft 01-structure.ttl from the introspection brief.

This writes a DRAFT, not a finished ontology. It gets the mechanical parts right — class per
table, a property per column bound to its physical name, a link per foreign key (composite
keys included), `:state "action"` left out on purpose — and it refuses to guess the things a
human must decide:

  * whether a table is an object or an association (it prints the question)
  * what a metric MEANS (there are no metrics in the draft)
  * which properties a write may own (`:state "action"` is never invented)

Column names are kept verbatim in `:physicalColumn`, but the RDF local name is de-columned:
`l_extendedprice` -> `:lExtendedprice`? No — the skill's rule is "name the property after the
QUESTION, not the column", so the draft uses the column name only as a placeholder and marks
every property it wrote with `# TODO name after the question` unless the column is already a
plain noun (name, price, city, status, kind, version, zone).

Usage:
    python scaffold_ttl.py --brief brief.json --ns https://example.org/onto# \
        --out 01-structure.ttl
"""
from __future__ import annotations

import argparse
import json
import re
import sys

# columns whose name is already the word a person would ask for
PLAIN = {"id", "name", "price", "cost", "amount", "city", "count", "status", "kind",
         "version", "zone", "type", "code", "value", "score", "weight", "volume",
         "capacity", "date", "time", "reason", "category", "region", "country", "age"}

TYPE_MAP = [
    (r"^bigint|^integer|^smallint|^int", "xsd:integer"),
    (r"^numeric|^decimal|^real|^double", "xsd:decimal"),
    (r"^bool", "xsd:boolean"),
    (r"^date$", "xsd:date"),
    (r"^timestamp|^timestamptz", "xsd:dateTime"),
    (r"^time", "xsd:time"),
    (r"^text|^character|^varchar|^json", "xsd:string"),
]


def camel(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:] if p)
    return out or name


def cls_name(table: str) -> str:
    words = re.split(r"[^A-Za-z0-9]+", table)
    out = "".join(w[:1].upper() + w[1:].lower() for w in words if w)
    # a trailing plural is a table convention, not a class name
    return out[:-1] if out.endswith("s") and not out.endswith("ss") else out


def xsd(t: str) -> str:
    for pattern, mapping in TYPE_MAP:
        if re.search(pattern, t.strip().lower()):
            return mapping
    return "xsd:string"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--brief", required=True)
    ap.add_argument("--ns", required=True)
    ap.add_argument("--out", default="")
    args = ap.parse_args()

    brief = json.load(open(args.brief, encoding="utf-8"))

    # ---- names must be unique across the ontology -------------------------------------
    # In RDF the same local name is ONE property: `:id` on six classes becomes a property
    # with six domains, and the compiler then refuses it as ambiguous everywhere. So a name
    # that repeats gets prefixed with its class (`:appointmentId`), which is also how a
    # person names it in a question.
    def prop_owner_map() -> dict[str, list[str]]:
        owners: dict[str, list[str]] = {}
        for t in brief["tables"]:
            cls = cls_name(t["table"])
            fk_cols = {c for f in t["foreign_keys"] for c in f["columns"]}
            for c in t["columns"]:
                if c["column"] in fk_cols:
                    continue          # a FK column becomes the link, not a data property
                owners.setdefault(camel(c["column"]), []).append(cls)
            for fk in t["foreign_keys"]:
                name = camel(fk["columns"][0].removesuffix("_id") or fk["columns"][0])
                owners.setdefault(name, []).append(cls)
        return owners

    owners = prop_owner_map()
    used: dict[str, str] = {}          # final name -> owner class

    def unique(base: str, cls: str) -> str:
        name = base
        if owners.get(base, []) != [cls] or base in used:
            name = cls[:1].lower() + cls[1:] + base[:1].upper() + base[1:]
        while name in used:
            name = name + "2"
        used[name] = cls
        return name

    lines = [
        f"# DRAFT — generated by scaffold_ttl.py from {args.brief}",
        "#",
        "# Not automated on purpose: object-vs-association, metric meaning,",
        "# which properties a write owns (:state \"action\"), and every display name.",
        "",
        f"@prefix : <{args.ns}> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
        "# ---------------------------------------------------------------- objects",
    ]
    questions: list[str] = []
    for t in brief["tables"]:
        name = cls_name(t["table"])
        pk = ", ".join(t["primary_key"]) or "id"
        lines.append(f':{name} a owl:Class ; rdfs:label "{t["table"]}" ;')
        lines.append(f'    :physicalTable "{t["table"]}" ; :primaryKey "{pk}" .')
        if len(t["primary_key"]) > 1:
            lines.append(f'# NOTE :{name} has a composite key ({pk}) — the compiler joins and '
                         f'counts on it as a tuple')
        if t.get("shape_question"):
            questions.append(f"{t['table']}: {t['shape_question']}")
        lines.append("")

    lines.append("# ---------------------------------------------------------------- properties")
    for t in brief["tables"]:
        name = cls_name(t["table"])
        fk_cols = {c for f in t["foreign_keys"] for c in f["columns"]}
        for c in t["columns"]:
            if c["column"] in fk_cols:
                # the FK *is* the link below; declaring it again as data would make the same
                # relationship two things (and the name collide with the target's own column)
                continue
            prop = unique(camel(c["column"]), name)
            todo = "" if prop.lower().endswith(camel(c["column"]).lower()) else ""
            lines.append(f':{prop} a owl:DatatypeProperty ; rdfs:domain :{name} ; '
                         f'rdfs:range {xsd(c["type"])} ;')
            lines.append(f'    :physicalColumn "{c["column"]}" .{todo}')
    lines.append("")

    lines.append("# ---------------------------------------------------------------- links")
    for t in brief["tables"]:
        name = cls_name(t["table"])
        for fk in t["foreign_keys"]:
            target = cls_name(fk["references"])
            prop = unique(camel(fk["columns"][0].removesuffix("_id") or fk["columns"][0]), name)
            lines.append(f':{prop} a owl:ObjectProperty ; rdfs:domain :{name} ; '
                         f'rdfs:range :{target} ;')
            if len(fk["columns"]) == 1:
                lines.append(f'    :physicalColumn "{fk["columns"][0]}" ; '
                             f':references :{target} .')
            else:
                lines.append(f'    :physicalColumn "{", ".join(fk["columns"])}" ; '
                             f':referencesKey "{", ".join(fk["reference_columns"])}" ; '
                             f':references :{target} .')
                lines.append("# NOTE composite link: BOTH columns are joined; half a key "
                             "would multiply the rows")
    lines.append("")

    text = "\n".join(lines) + "\n"
    if args.out:
        open(args.out, "w", encoding="utf-8").write(text)
        print(f"wrote {args.out}")
    else:
        print(text)
    if questions:
        print("\n# Questions this draft does NOT answer — take them to the human:")
        for q in questions:
            print("  -", q)
    return 0


if __name__ == "__main__":
    sys.exit(main())
